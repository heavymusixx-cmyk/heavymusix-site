function fmtDate(d){
  const [y,m,day] = d.split("-").map(Number);
  return new Date(y, m-1, day).toLocaleDateString("en-US",{month:"long",day:"numeric",year:"numeric"});
}
function esc(s){return String(s).replace(/[&<>"]/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;","\"":"&quot;"}[c]));}

/* Each story has its own page: news/<slug>.html (built by scripts/build_pages.py) */
function slugOf(n){return n.date+"-"+n.title.toLowerCase().replace(/[^a-z0-9]+/g,"-").replace(/^-|-$/g,"").slice(0,60);}
function storyUrl(n){return "news/"+slugOf(n)+".html";}
function bodyHtml(n){return n.text.map(p=>/^Source:/i.test(p)?`<p class="src">${esc(p)}</p>`:`<p>${esc(p)}</p>`).join("");}

/* Home page: latest 6 headlines, each opening our own story */
function renderLatest(el){
  el.innerHTML = NEWS.slice(0,6).map(n=>`
    <div class="card">
      <span class="tag">${esc(n.tag)}</span>
      <div class="date">${fmtDate(n.date)}</div>
      <h3><a class="hl" href="${storyUrl(n)}">${esc(n.title)}</a></h3>
      <p class="muted">${esc(n.text[0])}</p>
      <a href="${storyUrl(n)}">Read the story</a>
    </div>`).join("");
}
/* News page: search + category buttons, then every matching headline, newest first */
function renderAll(el){
  var tags = ["All"].concat(NEWS.map(function(n){return n.tag;}).filter(function(t,i,a){return a.indexOf(t)===i;}));
  el.innerHTML =
    '<form class="finder newsfind" onsubmit="return false" role="search">' +
    '<label for="nq">Search the news</label>' +
    '<input id="nq" type="search" placeholder="Try Jinjer, Trivium, tour, Arizona, new album" autocomplete="off">' +
    '<div class="tagbtns">' + tags.map(function(t,i){return '<button type="button" class="tagbtn' + (i===0?' on':'') + '" aria-pressed="' + (i===0) + '" data-t="' + esc(t) + '">' + esc(t) + '</button>';}).join("") + '</div></form>' +
    '<p id="newscount" class="muted" aria-live="polite"></p><div id="newslist"></div>' +
    '<div class="btns"><button type="button" class="btn ghost" id="newsmore" hidden>Show more stories</button></div>';
  var q = el.querySelector("#nq"), out = el.querySelector("#newslist"), tag = "All", PAGE = 12, shown = PAGE;
  var more = el.querySelector("#newsmore"), count = el.querySelector("#newscount");
  more.addEventListener("click", function(){
    var first = shown; shown += PAGE; draw(true);
    var next = out.querySelectorAll("article")[first]; if (next){ var a = next.querySelector("a.hl"); if (a) a.focus(); }
  });
  function draw(keep){
    if (!keep) shown = PAGE;
    var term = q.value.trim().toLowerCase();
    var list = NEWS.filter(function(n){
      if (tag !== "All" && n.tag !== tag) return false;
      return !term || (n.title + " " + n.tag + " " + n.text.join(" ")).toLowerCase().indexOf(term) > -1;
    });
    count.textContent = list.length ? "Showing " + Math.min(shown, list.length) + " of " + list.length + " stories" : "";
    more.hidden = list.length <= shown;
    out.innerHTML = list.length ? list.slice(0, shown).map(function(n){return `
    <article class="post">
      <span class="tag">${esc(n.tag)}</span>
      <div class="date muted">${fmtDate(n.date)}</div>
      <h2><a class="hl" href="${storyUrl(n)}">${esc(n.title)}</a></h2>
      <p>${esc(n.text[0])}</p>
      <a href="${storyUrl(n)}">Read the story</a>
    </article>`;}).join("") : '<p class="lead">No stories match that yet. Try a band, a city, or a word like tour or album.</p>';
  }
  q.addEventListener("input", draw);
  el.querySelectorAll(".tagbtn").forEach(function(b){ b.addEventListener("click", function(){
    tag = b.dataset.t; el.querySelectorAll(".tagbtn").forEach(function(x){ x.classList.toggle("on", x === b); x.setAttribute("aria-pressed", x === b); }); draw();
  }); });
  var pre = new URLSearchParams(location.search).get("q"); if (pre) q.value = pre;
  draw();
}
/* Story page: the full HeavyMusix story, plus more headlines */
function renderArticle(el){
  const p=new URLSearchParams(location.search).get("p");
  const n=NEWS.find(x=>slugOf(x)===p)||NEWS[0];
  document.title=n.title+" | HeavyMusix";
  const more=NEWS.filter(x=>x!==n).slice(0,6);
  el.innerHTML=`
    <article class="post story">
      <span class="tag">${esc(n.tag)}</span>
      <div class="date muted">${fmtDate(n.date)}</div>
      <h1>${esc(n.title)}</h1>
      ${bodyHtml(n)}
    </article>
    <h2 class="sub">More metal news</h2>
    <ul class="morenews">${more.map(m=>`<li><a href="${storyUrl(m)}">${esc(m.title)}</a><span class="wsrc">${fmtDate(m.date)}</span></li>`).join("")}</ul>
    <div class="btns"><a class="btn ghost" href="news.html">All news</a></div>`;
}
